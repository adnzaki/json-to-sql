import type { ForeignKeyRelation, TableDefinition } from '../types/schema';

/**
 * Generate DBML (Database Markup Language)
 */
export function generateDbml(
  tables: TableDefinition[],
  relations: ForeignKeyRelation[]
): string {
  const lines: string[] = [];
  lines.push('// Generated by SchemaCraft');
  lines.push('');

  tables.forEach((table) => {
    lines.push(`Table ${table.name} {`);
    table.columns.forEach((col) => {
      const settings: string[] = [];
      if (col.isPrimaryKey) settings.push('pk');
      if (col.isAutoIncrement) settings.push('increment');
      if (col.isUnique && !col.isPrimaryKey) settings.push('unique');
      if (!col.isNullable && !col.isPrimaryKey) settings.push('not null');
      if (col.defaultValue) settings.push(`default: \`${col.defaultValue}\``);
      if (col.comment) settings.push(`note: '${col.comment}'`);

      const settingStr = settings.length > 0 ? ` [${settings.join(', ')}]` : '';
      const typeStr = col.lengthOrPrecision
        ? `${col.dataType.toLowerCase()}(${col.lengthOrPrecision})`
        : col.dataType.toLowerCase();

      lines.push(`  ${col.name} ${typeStr}${settingStr}`);
    });
    if (table.comment) {
      lines.push(`  Note: '${table.comment}'`);
    }
    lines.push('}\n');
  });

  if (relations.length > 0) {
    lines.push('// Relationships');
    relations.forEach((rel) => {
      lines.push(`Ref: ${rel.fromTable}.${rel.fromColumn} > ${rel.toTable}.${rel.toColumn}`);
    });
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Generate Prisma Schema (`schema.prisma`)
 */
export function generatePrismaSchema(
  tables: TableDefinition[],
  relations: ForeignKeyRelation[],
  datasourceProvider: 'mysql' | 'postgresql' = 'mysql'
): string {
  const lines: string[] = [];
  lines.push(`datasource db {`);
  lines.push(`  provider = "${datasourceProvider}"`);
  lines.push(`  url      = env("DATABASE_URL")`);
  lines.push(`}\n`);
  lines.push(`generator client {`);
  lines.push(`  provider = "prisma-client-js"`);
  lines.push(`}\n`);

  tables.forEach((table) => {
    const modelName = toPascalCase(table.name);
    lines.push(`model ${modelName} {`);

    table.columns.forEach((col) => {
      let prismaType = 'String';
      switch (col.dataType) {
        case 'INT':
        case 'SMALLINT':
        case 'SERIAL':
          prismaType = 'Int';
          break;
        case 'BIGINT':
        case 'BIGSERIAL':
          prismaType = 'BigInt';
          break;
        case 'DECIMAL':
        case 'FLOAT':
        case 'DOUBLE':
          prismaType = 'Float';
          break;
        case 'BOOLEAN':
          prismaType = 'Boolean';
          break;
        case 'DATE':
        case 'DATETIME':
        case 'TIMESTAMP':
          prismaType = 'DateTime';
          break;
        case 'JSON':
        case 'JSONB':
          prismaType = 'Json';
          break;
        default:
          prismaType = 'String';
      }

      if (col.isNullable && !col.isPrimaryKey) {
        prismaType += '?';
      }

      const attributes: string[] = [];
      if (col.isPrimaryKey) {
        attributes.push(col.isAutoIncrement ? '@id @default(autoincrement())' : '@id');
      }
      if (col.isUnique && !col.isPrimaryKey) {
        attributes.push('@unique');
      }
      if (col.defaultValue === 'CURRENT_TIMESTAMP') {
        attributes.push('@default(now())');
      }

      const attrStr = attributes.length > 0 ? ` ${attributes.join(' ')}` : '';
      lines.push(`  ${col.name} ${prismaType}${attrStr}`);
    });

    lines.push(`  @@map("${table.name}")`);
    lines.push(`}\n`);
  });

  return lines.join('\n');
}

/**
 * Generate TypeScript Interfaces
 */
export function generateTypeScriptInterfaces(tables: TableDefinition[]): string {
  const lines: string[] = [];
  lines.push('// Generated by SchemaCraft - TypeScript Models\n');

  tables.forEach((table) => {
    const interfaceName = toPascalCase(table.name);
    lines.push(`export interface ${interfaceName} {`);

    table.columns.forEach((col) => {
      let tsType = 'string';
      switch (col.dataType) {
        case 'INT':
        case 'BIGINT':
        case 'SMALLINT':
        case 'DECIMAL':
        case 'FLOAT':
        case 'DOUBLE':
        case 'SERIAL':
        case 'BIGSERIAL':
          tsType = 'number';
          break;
        case 'BOOLEAN':
          tsType = 'boolean';
          break;
        case 'DATE':
        case 'DATETIME':
        case 'TIMESTAMP':
          tsType = 'Date | string';
          break;
        case 'JSON':
        case 'JSONB':
          tsType = 'Record<string, any> | any[]';
          break;
        default:
          tsType = 'string';
      }

      const optional = col.isNullable ? '?' : '';
      lines.push(`  ${col.name}${optional}: ${tsType};`);
    });

    lines.push(`}\n`);
  });

  return lines.join('\n');
}

function toPascalCase(str: string): string {
  return str
    .replace(/(?:^\w|[A-Z]|\b\w)/g, (letter) => letter.toUpperCase())
    .replace(/[\s_-]+/g, '');
}
